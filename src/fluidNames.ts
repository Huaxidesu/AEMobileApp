/** 流体 id → 中文名；查不到返回 null（交给上层用服务端给的英文名兜底） */
export function fluidName(id: string): string | null {
  const base = id.replace(/^(molten|plasma|liquid|gas|fluid)\./i, '').toLowerCase();
  const cn = MATERIAL_NAMES[base];
  if (!cn) return null;
  if (/^molten\./i.test(id)) return '熔融' + cn;
  if (/^plasma\./i.test(id)) return '等离子' + cn;
  return cn;
}
